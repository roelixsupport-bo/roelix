on conflict (method_key) do nothing;

alter table public.orders
  add column if not exists payment_method text not null default 'cod',
  add column if not exists payment_receipt_path text;

alter table public.orders
  drop constraint if exists orders_payment_method_check,
  drop constraint if exists orders_manual_payment_receipt_check,
  add constraint orders_payment_method_check
    check (payment_method in ('cod', 'vodafone_cash', 'instapay')),
  add constraint orders_manual_payment_receipt_check
    check (
      (payment_method = 'cod' and payment_receipt_path is null)
      or (payment_method in ('vodafone_cash', 'instapay') and payment_receipt_path is not null)
    );

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'payment-receipts',
  'payment-receipts',
  false,
  8388608,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Customers can upload payment receipts" on storage.objects;
create policy "Customers can upload payment receipts"
  on storage.objects for insert
  to anon, authenticated
  with check (
    bucket_id = 'payment-receipts'
    and name ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|jpeg|png|webp)$'
  );

drop policy if exists "Admins can read payment receipts" on storage.objects;
create policy "Admins can read payment receipts"
  on storage.objects for select
  to authenticated
  using (bucket_id = 'payment-receipts' and public.is_roelix_admin());

drop policy if exists "Admins can delete payment receipts" on storage.objects;
create policy "Admins can delete payment receipts"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'payment-receipts' and public.is_roelix_admin());

drop policy if exists "Allow public order submissions" on public.orders;
create policy "Allow public order submissions"
  on public.orders for insert
  to anon, authenticated
  with check (
    status = 'pending'
    and (
      payment_method = 'cod'
      or exists (
        select 1
        from public.payment_settings
        where method_key = payment_method
          and is_active
      )
    )
  );

