create table if not exists public.payment_settings (
  id bigint generated by default as identity primary key,
  method_key text not null unique
    check (method_key in ('vodafone_cash', 'instapay')),
  method_name text not null check (length(btrim(method_name)) between 1 and 80),
  account_info text not null default '',
  is_active boolean not null default false,
  icon_url text,
  constraint payment_settings_active_account_check
    check (not is_active or length(btrim(account_info)) between 3 and 120)
);

alter table public.payment_settings enable row level security;
grant select on public.payment_settings to anon, authenticated;
grant insert, update, delete on public.payment_settings to authenticated;

drop policy if exists "Anyone can read active payment settings" on public.payment_settings;
create policy "Anyone can read active payment settings"
  on public.payment_settings for select
  to anon, authenticated
  using (is_active);

drop policy if exists "Admins can read all payment settings" on public.payment_settings;
create policy "Admins can read all payment settings"
  on public.payment_settings for select
  to authenticated
  using (public.is_roelix_admin());

drop policy if exists "Admins can insert payment settings" on public.payment_settings;
create policy "Admins can insert payment settings"
  on public.payment_settings for insert
  to authenticated
  with check (public.is_roelix_admin());

drop policy if exists "Admins can update payment settings" on public.payment_settings;
create policy "Admins can update payment settings"
  on public.payment_settings for update
  to authenticated
  using (public.is_roelix_admin())
  with check (public.is_roelix_admin());

drop policy if exists "Admins can delete payment settings" on public.payment_settings;
create policy "Admins can delete payment settings"
  on public.payment_settings for delete
  to authenticated
  using (public.is_roelix_admin());

